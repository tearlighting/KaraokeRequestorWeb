export type MessageKey = keyof typeof ja | keyof typeof ux.ja;
export type Messages = Record<MessageKey, string>;
export const dictionaries: Record<Locale, Messages> = {
  ja: { ...ja, ...ux.ja }, 'zh-CN': { ...zh, ...ux['zh-CN'] }, en: { ...en, ...ux.en },
};
export { ja as jp, zh, en };
export function translate(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  let value = dictionaries[locale]?.[key] ?? dictionaries.ja[key] ?? key;
  if (import.meta.env?.DEV && !(key in dictionaries[locale])) console.warn(`[i18n] Missing key: ${key} (${locale})`);
  for (const [name, replacement] of Object.entries(values ?? {})) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}
